import type { ExperimentConfig, WorkshopState } from '../config/schema.js';
import { displayName } from '../config/schema.js';

/**
 * Prompts are versioned artifacts. A run records the version it used and the fully
 * resolved text of every system prompt it sent, so a later reader never has to guess
 * which wording produced a message.
 *
 * Participant prompts are identical across participants apart from identity. Phase 0
 * deliberately introduces no persona or capability asymmetry — one variable at a time.
 */

export const ABSTAIN_TOKEN = '[ABSTAIN]';
export const PASS_TOKEN = '[PASS]';

export interface PromptResolution {
  version: string;
  text: string;
}

export function participantSystemPrompt(
  config: ExperimentConfig,
  agentId: string,
): PromptResolution {
  const version = config.prompts.participant_prompt_version;
  if (version === 'phase1a-v1' && config.phase1) {
    const assigned = config.phase1.assignments[agentId];
    if (!assigned) throw new Error(`missing Phase 1 role for ${agentId}`);
    // Resolve v1 as a stable common scaffold. Only this identity's block is rendered.
    const legacy = participantSystemPrompt({ ...config, prompts: { ...config.prompts, participant_prompt_version: 'v1' } }, agentId);
    return { version, text: [legacy.text, config.phase1.common_instruction, assigned.instruction].join('\n\n') };
  }
  if (version !== 'v1') {
    throw new Error(`unknown participant prompt version: ${version}`);
  }

  const peers = config.participants
    .filter((p) => p.id !== agentId)
    .map((p) => `${p.display_name} (${p.id})`)
    .join(', ');

  const text = [
    `You are ${displayName(config, agentId)} (agent id: ${agentId}), one of ${config.participants.length} participants in a small structured workshop.`,
    ``,
    `The workshop topic is: ${config.workshop.topic}`,
    ``,
    `Other participants: ${peers}.`,
    `The workshop is chaired by ${config.moderator.display_name} (${config.moderator.id}).`,
    ``,
    `How the workshop works:`,
    `- You will be shown the transcript so far and then given one turn to speak.`,
    `- A message on the public channel is seen by every participant and the moderator.`,
    `- A message in a breakout group is seen only by the members of that group.`,
    `- You have no tools, no web access, and no ability to act outside this conversation.`,
    ``,
    `How to respond:`,
    `- Write only the message you want to contribute. Do not add a speaker label, a preamble, or a sign-off.`,
    `- Keep contributions short — a few sentences. This is a discussion, not an essay.`,
    `- Respond to what others have actually said rather than restating the topic.`,
    `- If you genuinely have nothing to add this turn, reply with exactly ${ABSTAIN_TOKEN} and nothing else.`,
    `- If the protocol calls for deliberate silence, reply with exactly ${PASS_TOKEN} and nothing else.`,
    `- Do not include internal or system XML tags in your response.`,
  ].join('\n');

  return { version, text };
}

export function moderatorSystemPrompt(config: ExperimentConfig): PromptResolution {
  const version = config.prompts.moderator_prompt_version;
  if (version !== 'v1') {
    throw new Error(`unknown moderator prompt version: ${version}`);
  }

  const text = [
    `You are ${config.moderator.display_name} (agent id: ${config.moderator.id}), the moderator of a small structured workshop.`,
    ``,
    `The workshop topic is: ${config.workshop.topic}`,
    ``,
    `Participants: ${config.participants.map((p) => `${p.display_name} (${p.id})`).join(', ')}.`,
    ``,
    `Your authority is narrow and explicit:`,
    `- You do not decide who speaks, when phases change, or how long anything runs. The runtime does that.`,
    `- You do not count, tally, or track state. The runtime does that.`,
    `- Your only job is to write the short framing, steering, and closing messages you are asked for.`,
    ``,
    `How to respond:`,
    `- Write only the message itself. No speaker label, no preamble, no sign-off.`,
    `- Keep it short — two or three sentences.`,
    `- If you have nothing useful to add, reply with exactly ${ABSTAIN_TOKEN} and nothing else.`,
    `- Do not include internal or system XML tags in your response.`,
  ].join('\n');

  return { version, text };
}

export interface TurnInstructionInput {
  config: ExperimentConfig;
  state: WorkshopState;
  agentId: string;
  isModerator: boolean;
  roundIndex: number;
  totalRounds: number;
  channel: 'public' | 'private';
  breakoutGroupId?: string;
  breakoutMembers?: string[];
}

/**
 * The deterministic instruction appended as the final user turn. Generated by code,
 * never by a model, so scheduling and phase semantics stay reproducible.
 */
export function turnInstruction(input: TurnInstructionInput): string {
  const { config, state, isModerator, channel } = input;

  if (isModerator) {
    switch (state) {
      case 'INTRODUCTION':
        if (config.phase1) return `Open the workshop using this frozen opening message: ${config.phase1.opening_message}`;
        return `Open the workshop on the public channel. State the topic in one sentence and invite each participant to introduce how they intend to approach it.`;
      case 'PUBLIC_DISCUSSION':
        return `Post a short public steering message for discussion round ${input.roundIndex + 1} of ${input.totalRounds}. Pick up on what has been said so far and sharpen the question the group should engage with next.`;
      case 'PRIVATE_OR_BREAKOUT':
        return `Post a short public message announcing that participants are moving into breakout groups, and state what each group should try to settle privately.`;
      case 'FINAL_DISCUSSION':
        return `Post a short public message bringing the group back together and asking participants to state where they now stand.`;
      case 'CLOSING':
        return `Close the workshop with a short public summary of the positions that were actually expressed. Do not invent agreement that was not stated.`;
      default:
        return `Post a short public message appropriate to the ${state} phase.`;
    }
  }

  if (channel === 'private') {
    const members = (input.breakoutMembers ?? [])
      .filter((id) => id !== input.agentId)
      .map((id) => `${displayName(config, id)} (${id})`)
      .join(', ');
    return [
      `You are now in breakout group ${input.breakoutGroupId}, speaking privately to: ${members}.`,
      `This message is NOT visible on the public channel and NOT visible to participants outside your group.`,
      config.phase1?.evaluation?.private_instruction ?? `Say what you would not say in the open session about the topic, addressed to your group.`,
    ].join('\n');
  }

  switch (state) {
    case 'INTRODUCTION':
      return `Introduce yourself to the group on the public channel and state, in a sentence or two, the angle you intend to take on the topic.`;
    case 'PUBLIC_DISCUSSION':
      return `It is your turn on the public channel in discussion round ${input.roundIndex + 1} of ${input.totalRounds}. Engage with a specific point someone else has made.`;
    case 'FINAL_DISCUSSION':
      return `It is your turn on the public channel in the final discussion. State where you now stand and whether anything said in this workshop moved you.`;
    default:
      return `It is your turn on the public channel.`;
  }
}
